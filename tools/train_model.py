def _git_commit() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True,
            timeout=10,
        )
        return out.stdout.strip() if out.returncode == 0 else "unknown"
    except Exception:
        return "unknown"


def _status_inline(t: float, v: float, chute: bool, landed: bool,
                   boost_time: float) -> str:
    """Status as FlightSimulator.status() would decide it, from live state.

    Same decision order as the simulator (landed / t==0 / boost / chute /
    v>0), without a second integration pass.
    """
    if landed:
        return proto.STATUS_LANDED
    if t == 0.0:
        return proto.STATUS_PRE_LAUNCH
    if t < boost_time:
        return proto.STATUS_BOOST
    if chute:
        return proto.STATUS_PARACHUTE
    return proto.STATUS_ASCENT if v > 0 else proto.STATUS_DESCENT


def _band_of(alt: float) -> str:
    """Altitude-band label for ellipse/confidence bucketing."""
    for lo, hi, label in ALT_BANDS:
        if lo <= alt < hi:
            return label
    return ALT_BANDS[-1][2]


def _simulate_one(lo_hi: dict) -> tuple[np.ndarray, dict]:
    """One randomized flight through FlightSimulator.

    Returns (feature_matrix, targets) where targets holds per-row arrays
    for eta_s / v_landing_m_s / apogee_m (constant per flight for the
    latter) / land_x / land_y (constant per flight).

    The 0.5 s sensor windows and the running flight max (alt_hist_max) are
    maintained at PHYSICS rate (every `step()`), exactly as the GCS rolling
    buffer maintains them live (it holds every 50 Hz frame of the flight) —
    so training and serving build the same features from the same noise.
    The lateral features use the same state the physics just integrated
    (x/y/vx/vy_lat after the step; wx/wy at the same t the physics used).
    """
    sim = FlightSimulator(FlightParams(**lo_hi))
    sim.flight = 1
    sim._reset()
    bt = lo_hi["boost_time"]

    ts: list[float] = []
    st_mask: list[int] = []   # status index per row (STATUS_ORDER position)
    rows: list[list[float]] = []
    # 0.5 s sensor windows, fed at PHYSICS rate (every step) — the GCS rolling
    # buffer does exactly the same thing live, so train == serve.
    alt_win: deque = deque(maxlen=HIST_LEN)
    vel_win: deque = deque(maxlen=HIST_LEN)
    acc_win: deque = deque(maxlen=HIST_LEN)
    # running flight state (apogee bookkeeping) — the GCS keeps the same
    # running max of its own (noisy) altitude buffer live.
    alt_run_max = 0.0

    def feed_window(s: dict) -> None:
        # feed the windows at PHYSICS rate (every step) even for rows that
        # are not sampled (0.5 s window spans 25 steps, rows every 5); the
        # running flight max is the same — the GCS buffer holds every
        # 50 Hz frame, so training must see every one too.
        nonlocal alt_run_max
        alt_win.append(s["altitude"])
        vel_win.append(s["velocity"])
        acc_win.append(s["accel"])
        alt_run_max = max(alt_run_max, s["altitude"])

    def sample_row(s: dict, status: str) -> None:
        nonlocal alt_run_max
        alt_win.append(s["altitude"])
        vel_win.append(s["velocity"])
        acc_win.append(s["accel"])
        alt_run_max = max(alt_run_max, s["altitude"])
        m_alt = float(np.mean(alt_win))
        m_vel = float(np.mean(vel_win))
        m_acc = float(np.mean(acc_win))
        # ACTIVE quadratic drag coefficient, sign-consistent (>= 0) whether
        # climbing or falling: while unpowered the specific force equals
        # -K*v^2 (thrust off, gravity cancels), so -m_acc/m_vel^2 recovers
        # drag_k in ASCENT/DESCENT and chute_drag_k in PARACHUTE from the
        # smoothed signals. The trees gate it with the status one-hot (it is
        # meaningless during BOOST, where the engine dominates).
        k_active = max(0.0, -m_acc) / max(m_vel ** 2, 1.0)
        in_climb = status in (proto.STATUS_BOOST, proto.STATUS_ASCENT)
        v_climb = max(m_vel, 0.0) if in_climb else 0.0
        # analytic vacuum-with-current-drag climb priors: remaining time to
        # apogee and remaining climb (from the smoothed signals; 0 once the
        # rocket has stopped climbing). Together with the running altitude
        # max they anchor the apogee target in EVERY phase, including
        # PRE-LAUNCH/BOOST (where nothing is known yet) and PARACHUTE
        # (where the smoothed altitude is still biased low).
        if k_active < 1e-9 or not in_climb:
            climb_t = v_climb / GRAVITY if in_climb else 0.0
            climb_h = (v_climb ** 2) / (2.0 * GRAVITY) if in_climb else 0.0
        else:
            climb_t = 1.0 / k_active * math.acos(1.0 / max(1.0 + k_active * v_climb / GRAVITY, 1.0))
            climb_h = 1.0 / k_active * math.log(1.0 + k_active * v_climb / GRAVITY)
        # Phase 4 lateral features — the same state the physics just used.
        wx, wy = sim.wind()
        rows.append([
            sim.t, s["altitude"], s["velocity"], s["accel"],
            s["pressure"], s["temperature"],
            m_alt, m_vel, m_acc, k_active,
            1.0 if status == proto.STATUS_PRE_LAUNCH else 0.0,
            1.0 if status == proto.STATUS_BOOST else 0.0,
            1.0 if status == proto.STATUS_ASCENT else 0.0,
            1.0 if status == proto.STATUS_DESCENT else 0.0,
            1.0 if status == proto.STATUS_PARACHUTE else 0.0,
            1.0 if status == proto.STATUS_LANDED else 0.0,
            max(0.0, sim.t - bt),
            math.sqrt(2.0 * max(m_alt, 0.0) / GRAVITY),   # vacuum-freefall ETA prior
            climb_t, climb_h,
            alt_run_max,
            sim.x, sim.y_lat, sim.vx, sim.vy_lat,
            sim.p.wind_speed, wx, wy,
            2.0 * math.pi * sim.t / GUST_PERIOD,   # gust phase (computable from t)
        ])
        ts.append(sim.t)
        st_mask.append(STATUS_ORDER.index(status))

    sample_row(sim.sensor_readings(),
               _status_inline(sim.t, sim.v, sim.chute, sim.landed, bt))  # t=0
    idx = 0
    while not sim.landed:
        sim.step()
        idx += 1
        s = sim.sensor_readings()
        if idx % SAMPLE_EVERY != 0:
            feed_window(s)
            continue
        sample_row(s, _status_inline(sim.t, sim.v, sim.chute, sim.landed, bt))
    # step() has just zeroed y/v and set landed. The true impact velocity is
    # v of the state BEFORE that final step — recovered by deterministic
    # re-integration (see _impact_velocity).
    impact_v = _impact_velocity(sim)
    sample_row(sim.sensor_readings(), proto.STATUS_LANDED)

    land_t = sim.t
    land_x, land_y = sim.x, sim.y_lat     # touchdown site (ground truth)
    apogee = _apogee(sim)

    n = len(rows)
    matrix = np.asarray(rows, dtype=np.float64)
    assert matrix.shape == (n, len(FEATURE_NAMES)), matrix.shape
    targets = {
        "eta_s": np.maximum(0.0, land_t - np.array(ts)),
        "v_landing_m_s": np.full(n, impact_v),
        "apogee_m": np.full(n, apogee),
        "land_x": np.full(n, land_x),
        "land_y": np.full(n, land_y),
    }
    return matrix, targets


def _impact_velocity(sim: FlightSimulator) -> float:
    """True impact velocity (negative, m/s) for `sim`'s parameters.

    Re-integrates the same deterministic flight on a scratch instance and
    keeps v of the last in-flight step (the landing step zeroes v). Physics
    has no stochastic ground-truth component, so this is exact.
    """
    r = FlightSimulator(sim.p)
    v_last = 0.0
    while not r.landed:
        r.step()
        if not r.landed:
            v_last = r.v
    return v_last


def _apogee(sim: FlightSimulator) -> float:
    """True peak altitude (m): deterministic re-integration of the same flight."""
    r = FlightSimulator(sim.p)
    peak = 0.0
    while not r.landed:
        r.step()
        if r.y > peak:
            peak = r.y
    return peak


def generate(n_traj: int, seed: int) -> tuple[list[np.ndarray], list[dict]]:
    """Run `n_traj` randomized flights through FlightSimulator.

    The global `random` module (used by the simulator's sensor noise) is
    seeded from `seed`, so a full run is reproducible. The vertical
    trajectory itself is deterministic given the parameters; the gust is a
    pure function of t, so the only per-flight randomness on the ground-
    truth side is the parameter draw, and on the feature side the sensor
    noise.
    Returns (rows, targets) lists, one entry per trajectory.
    """
    random.seed(seed)
    rng = np.random.default_rng(seed)
    rows: list[np.ndarray] = []
    targets: list[dict] = []
    t0 = time.time()
    for i in range(n_traj):
        lo_hi = {k: float(rng.uniform(lo, hi)) for k, (lo, hi) in DISTRIBUTIONS.items()}
        m, tg = _simulate_one(lo_hi)
        rows.append(m)
        targets.append(tg)
        if (i + 1) % max(1, n_traj // 10) == 0:
            print(f"  generated {i + 1}/{n_traj} trajectories "
                  f"({time.time() - t0:.0f}s)", flush=True)
    return rows, targets


def _cov2(rx: np.ndarray, ry: np.ndarray) -> list[list[float]]:
    """2x2 residual covariance [[cxx, cxy], [cxy, cyy]] of (rx, ry)."""
    cx = float(np.mean(rx))
    cy = float(np.mean(ry))
    dx = rx - cx
    dy = ry - cy
    n = max(len(rx) - 1, 1)
    cxx = float(np.dot(dx, dx) / n)
    cyy = float(np.dot(dy, dy) / n)
    cxy = float(np.dot(dx, dy) / n)
    return [[cxx, cxy], [cxy, cyy]]


def _bucket_table(X_test: np.ndarray, eta_pred: np.ndarray,
                  eta_true: np.ndarray, site_pred: np.ndarray,
                  Y_test: dict) -> tuple[dict, dict]:
    """Per-(status, altitude-band) tables on the held-out test rows.

    Returns (bucket_eta_mae, ellipse_cov) where ellipse_cov holds 2x2
    residual covariances of (land_x, land_y) keyed "<STATUS>:<band>" plus
    "OVERALL". Buckets with fewer than MIN_BUCKET_ROWS rows are omitted
    from the ellipse table (the predictor falls back to OVERALL).
    """
    bands = np.array([_band_of(a) for a in X_test[:, ALT_COL]])
    eta_mae: dict[str, float] = {}
    cov: dict[str, list[list[float]]] = {}
    rx = site_pred[:, 0] - Y_test["land_x"]
    ry = site_pred[:, 1] - Y_test["land_y"]
    # overall (always stored — the serving fallback)
    cov["OVERALL"] = _cov2(rx, ry)
    eta_mae["OVERALL"] = float(np.mean(np.abs(eta_pred - eta_true)))
    for k, st in enumerate(STATUS_ORDER):
        for lo, hi, band in ALT_BANDS:
            mask = (X_test[:, STATUS_ONEHOT_OFFSET + k] == 1.0) & \
                   (X_test[:, ALT_COL] >= lo) & (X_test[:, ALT_COL] < hi)
            if mask.sum() == 0:
                continue
            key = f"{st}:{band}"
            eta_mae[key] = float(np.mean(np.abs(eta_pred[mask] - eta_true[mask])))
            if mask.sum() >= MIN_BUCKET_ROWS:
                cov[key] = _cov2(rx[mask], ry[mask])
    return eta_mae, cov


def main() -> None:
    ap = argparse.ArgumentParser(description="APEX-1 landing-prediction trainer (v2: landing site)")
    ap.add_argument("--seed", type=int, default=42, help="generation + split seed (default 42)")
    ap.add_argument("--quick", action="store_true", help="200 trajectories for fast iteration")
    ap.add_argument("--n-traj", type=int, default=None, help="override trajectory count")
    ap.add_argument("--test-frac", type=float, default=0.10, help="trajectory holdout fraction")
    args = ap.parse_args()

    n_traj = args.n_traj if args.n_traj is not None else (200 if args.quick else 2000)
    print(f"APEX-1 trainer v2: {n_traj} trajectories, seed={args.seed}, "
          f"test fraction={args.test_frac:.2f} (by trajectory)")

    t_start = time.time()
    rows, targets = generate(n_traj, seed=args.seed)
    t_gen = time.time() - t_start
    print(f"generation done in {t_gen:.1f}s")

    # --- trajectory-level split (rows of a flight never cross the split) ----
    rng = np.random.default_rng(args.seed + 1)
    order = rng.permutation(n_traj)
    n_test = max(1, int(round(n_traj * args.test_frac)))
    test_ids = set(order[:n_test].tolist())
    idx_train = [i for i in range(n_traj) if i not in test_ids]
    idx_test = [i for i in range(n_traj) if i in test_ids]

    X = np.vstack([rows[i] for i in idx_train])
    X_test = np.vstack([rows[i] for i in idx_test])
    Y = {t: np.concatenate([targets[i][t] for i in idx_train]) for t in TARGET_NAMES}
    Y_test = {t: np.concatenate([targets[i][t] for i in idx_test]) for t in TARGET_NAMES}
    print(f"rows: {X.shape[0]} train / {X_test.shape[0]} test "
          f"({len(idx_train)} train flights / {len(idx_test)} test flights)")

    # --- fit ---------------------------------------------------------------
    t0 = time.time()
    models = {}
    for j, tgt in enumerate(TARGET_NAMES):
        models[tgt] = HistGradientBoostingRegressor(
            **MODEL_HYPERPARAMS, random_state=args.seed + 100 + j)
        models[tgt].fit(X, Y[tgt])
    t_train = time.time() - t0
    print(f"training done in {t_train:.1f}s")

    # --- evaluate ----------------------------------------------------------
    report = {}
    ok = True
    print("\n=== TEST REPORT (held-out flights) ===")
    print("  (gate = achievable band, see FLAGGED DEVIATION docstring; "
          "spec = original target)")
    for tgt in TARGET_NAMES:
        pred = models[tgt].predict(X_test)
        mae = float(mean_absolute_error(Y_test[tgt], pred))
        r2 = float(r2_score(Y_test[tgt], pred))
        gate, spec = ACCEPT[tgt], SPEC_ACCEPT[tgt]
        passed = mae < gate
        ok &= passed
        report[tgt] = {"test_mae": mae, "test_r2": r2, "acceptance": gate,
                       "spec_acceptance": spec, "passed": passed}
        print(f"  {tgt:<14} MAE {mae:8.3f}  R2 {r2:8.4f}   "
              f"(gate < {gate} {'PASS' if passed else 'FAIL'}; "
              f"spec < {spec} {'PASS' if mae < spec else 'below-floor'})")

    # Per-status MAE of eta_s on the test rows (v1 profile, kept for the
    # record) and the Phase 4 per-(status, altitude-band) tables used for
    # the serving confidence and the ellipse.
    eta_pred = models["eta_s"].predict(X_test)
    overall_eta_mae = report["eta_s"]["test_mae"]
    status_mae: dict[str, float] = {}
    for k, name in enumerate(STATUS_ORDER):
        mask = X_test[:, STATUS_ONEHOT_OFFSET + k] == 1.0
        if mask.sum() >= 20:
            status_mae[name] = float(np.mean(
                np.abs(eta_pred[mask] - Y_test["eta_s"][mask])))
    print("  eta_s MAE by status:",
          "  ".join(f"{k} {v:.3f}" for k, v in status_mae.items()))

    # Confidence-ellipse data: bucketed residual covariance of the
    # (land_x, land_y) predictions on the held-out rows.
    site_pred = np.column_stack([
        models["land_x"].predict(X_test),
        models["land_y"].predict(X_test),
    ])
    bucket_eta_mae, ellipse_cov = _bucket_table(X_test, eta_pred,
                                                Y_test["eta_s"], site_pred,
                                                Y_test)
    print(f"  ellipse buckets: {len(ellipse_cov) - 1} + OVERALL "
          f"(min {MIN_BUCKET_ROWS} rows per bucket)")
    print("  bucket eta MAE (excerpts):")
    for key in ("DESCENT:100-200", "DESCENT:0-100", "PARACHUTE:0-100",
                "ASCENT:100-200", "OVERALL"):
        if key in bucket_eta_mae:
            print(f"    {key:<16} {bucket_eta_mae[key]:.3f} s")

    # --- artifacts ----------------------------------------------------------
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    # Phase 4 ships v2 as the single active model; delete the v1 pickle if
    # an old one is still around (retraining regenerates the active name).
    old = MODEL_DIR / "apex1_landing_v1.pkl"
    if old.exists():
        old.unlink()
    pkl_path = MODEL_DIR / PICKLE_NAME
    meta_path = MODEL_DIR / META_NAME
    payload = {
        "version": "apex1_landing_v2",
        "sklearn_version": sklearn.__version__,
        "models": {tgt: models[tgt] for tgt in TARGET_NAMES},
    }
    joblib.dump(payload, pkl_path)
    metadata = {
        "version": "apex1_landing_v2",
        "features": FEATURE_NAMES,
        "targets": TARGET_NAMES,
        "status_order": STATUS_ORDER,
        "distributions": {k: list(v) for k, v in DISTRIBUTIONS.items()},
        "gust": {"period_s": GUST_PERIOD, "amp": 0.15},
        "alt_bands": [[0.0, 100.0, "0-100"], [100.0, 200.0, "100-200"],
                      [200.0, 300.0, "200-300"]],
        "sample_every_frames": SAMPLE_EVERY,
        "n_trajectories": n_traj,
        "n_rows_train": int(X.shape[0]),
        "n_rows_test": int(X_test.shape[0]),
        "seed": args.seed,
        "test_frac": args.test_frac,
        "sklearn_version": sklearn.__version__,
        "git_commit": _git_commit(),
        "hyperparams": MODEL_HYPERPARAMS,
        "ellipse": ellipse_cov,
        "report": {
            "generation_s": round(t_gen, 2),
            "train_s": round(t_train, 2),
            "targets": report,
            "status_mae_eta": status_mae,
            "bucket_eta_mae": bucket_eta_mae,
            "overall_eta_mae": overall_eta_mae,
            "ellipse_min_bucket_rows": MIN_BUCKET_ROWS,
        },
    }
    meta_path.write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    pkl_mb = pkl_path.stat().st_size / 1e6
    print(f"\nartifacts: {pkl_path} ({pkl_mb:.2f} MB)  {meta_path}")
    print(f"total: {time.time() - t_start:.1f}s")
    if not ok:
        print("ACCEPTANCE GATE NOT MET — tune (more trees / features) and re-run.",
              file=sys.stderr)
        sys.exit(1)
    print("acceptance gate: ALL PASS "
          "(site targets: see FLAGGED DEVIATION note in docstring)")


if __name__ == "__main__":
    main()
