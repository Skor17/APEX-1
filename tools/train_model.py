"""APEX-1 landing-prediction trainer v2 — synthetic trajectories + HistGBM.

Phase 4: the GCS predicts, from live telemetry alone, *where and when* the
rocket will land. The flight is now 2-D (see simulator.py — wind-driven
lateral drift, launch tilt), and the model gains the landing SITE as a
target:

    eta_s          true seconds until landing, clamped >= 0
    v_landing_m_s  true impact velocity (m/s, negative = downward)
    apogee_m       true peak altitude of the flight [m]
    land_x         true touchdown position, downwind [m]
    land_y         true touchdown position, crosswind [m]

Five independent ``sklearn.ensemble.HistGradientBoostingRegressor``s are
fitted (one per target) into a single pickle, ``apex1_landing_v2.pkl``.

Training data is generated by driving the EXISTING ``FlightSimulator``
(``simulator.py`` — imported, never re-implemented) over randomized
parameter distributions around the real profile:

    thrust_accel   uniform 30.0 .. 50.0  m/s^2   (net, during boost)
    boost_time     uniform 1.5  .. 2.5  s
    drag_k         uniform 0.0006 .. 0.0015 1/m  (body, quadratic)
    chute_drag_k   uniform 0.10 .. 0.25  1/m     (chute, quadratic)
    chute_deploy   uniform 40.0 .. 70.0  m
    wind_speed     uniform 2.0  .. 12.0  m/s     (Phase 4)
    wind_dir_deg   uniform 0.0  .. 360.0 deg     (Phase 4, 0 = +x downwind)
    launch_tilt    uniform 0.0  .. 3.0   deg     (Phase 4, tilt-rail impulse)

Per-row sensor noise is whatever the simulator's own sensor model
(``sensor_readings()``) produces — the same BMP280/MPU6050 model the wire
uses, so the features the model learns from are exactly the features the
GCS sees live. One training row is sampled every 5 physics frames (10 Hz)
plus the t=0 PRE-LAUNCH row and the LANDED row. ~2000 trajectories ->
~450-550k rows.

Feature vector (29 columns, order fixed by FEATURE_NAMES — the exact same
columns prediction.py builds from a live frame + its rolling history, so
train/serve never diverge): the 21 v1 columns, unchanged in name and
order, followed by 8 Phase 4 lateral columns:

    t, altitude, velocity, accel, pressure, temperature,
    alt_hist, vel_hist, acc_hist, k_active,
    st_pre, st_boost, st_ascent, st_descent, st_parachute, st_landed,
    t_since_boost_end, t_ff, climb_prior, climb_h, alt_hist_max,
    x               downwind position [m] (ground truth on the wire — the
                          vehicle's estimated track, no GPS on board)
    y               crosswind position [m]
    vx              downwind velocity [m/s] (ground-relative)
    vy_lat          crosswind velocity [m/s] (ground-relative)
    wind_speed      the steady wind speed [m/s] the vehicle is flying in
                          (constant per flight; on the wire in `wind`)
    wx              current wind downwind component [m/s] INCLUDING the
                          deterministic gust (see below)
    wy              current wind crosswind component [m/s] (gust included)
    t_wind_phase    2*pi*t / GUST_PERIOD — the phase of the sinusoidal
                          gust (computable from t alone; the gust is
                          deterministic, so the model can "see" where the
                          wind is in its 7 s cycle). The gust law is
                          w(t) = wind_speed * (1 + 0.15 * sin(2*pi*t/7)).

At serving time the GCS reconstructs these 8 columns from the live frame
(x, y, wind) + history: vx/vy_lat by finite difference of the last two
same-flight lateral positions (the GCS buffer holds every 50 Hz frame),
wx/wy from the wind dict + the same deterministic gust at frame.t, and
t_wind_phase from frame.t — exactly the values the trainer sampled.
Legacy frames (x/y/wind = None, e.g. the ESP32) zero the lateral features:
the vertical targets stay valid, the site targets degrade (documented in
prediction.py).

Confidence ellipse (the Phase 4 "money" artifact): after fitting, the
trainer predicts land_x/land_y on the held-out test rows and buckets those
rows by (status, altitude band) — altitude bands 0–100 / 100–200 /
200–300 m (rows above 300 m fall in the top band). Per bucket it stores
the 2x2 residual covariance of the predicted-vs-true landing point:

    ellipse["<STATUS>:<band>"] = [[cxx, cxy], [cxy, cyy]]

plus the overall covariance as fallback. Buckets with fewer than
MIN_BUCKET_ROWS rows are not stored (the predictor falls back to the
overall). At serving time prediction.py eigen-decomposes the bucket
covariance (analytic 2x2) and reports the 1-sigma ellipse semi-axes
(ell_a >= ell_b) and the major-axis orientation ell_ang (radians, wrapped
to [-pi/2, pi/2)). The ellipse axes are the PRINCIPAL AXES of the
landing-point residual covariance — the HUD rotates the ellipse by
ell_ang to draw it. The same buckets carry the eta MAE
(``report.bucket_eta_mae``) that prediction.py turns into ``conf`` =
clamp(1 - eta_MAE_bucket/2, 0, 1).

Artifacts (written to <repo>/model/):
    apex1_landing_v2.pkl   joblib: {"version", "sklearn_version", "models": {...}}
    metadata.json          features/targets order, distributions, seed,
                           sklearn version, git commit, per-target test
                           MAE/R^2, the per-status eta MAE profile (v1),
                           the per-bucket eta MAE profile (Phase 4, for
                           conf), and the ellipse covariance table.

    The v1 pickle (apex1_landing_v1.pkl) is NOT shipped: v2 is the active
    model (same artifacts path contract, version bumped). Retraining via
    this script always regenerates the active artifacts.

Usage:
    python tools/train_model.py             # 2000 trajectories (full)
    python tools/train_model.py --quick     # 200 trajectories (fast iteration)
    python tools/train_model.py --seed 7    # reproducible generation + split

Acceptance (test MAE, gate of this run):
    eta_s < 1.0 s, v_landing < 1.0 m/s, apogee < 9.0 m  (v1 gates, kept)
    land_x < 1.5 m, land_y < 1.5 m                      (Phase 4, new)
"""
